"""Execution hooks for the four captured 3453 supervisors, guarded by code hash.

These describe the existing harness's DTE front-end stand-in, not an alternate
AT parser. The guest firmware still collects/parses commands and emits replies.
"""
from dataclasses import dataclass, field
from hashlib import sha256


@dataclass(frozen=True)
class Profile3453:
    name: str
    pc: dict[int, int] = field(default_factory=dict)  # canonical C normal -> actual CPU PC
    ram: dict[int, int] = field(default_factory=dict)
    command_callback: int = 0xA7B0
    empty_callback: int = 0x9138
    abort_rx_callback: int | None = None

    def address(self, canonical):
        return self.pc.get(canonical, canonical)


COMMON_BOOT_RAM = {0x2A8: 0x2A4, 0x2AA: 0x2A6, 0x2AC: 0x2A8, 0x2AE: 0x2AA,
                   0x6A2: 0x69A, 0x965: 0x959, 0x905: 0x8F9, 0x2712: 0x251E}


def profile_for(image):
    supervisor = getattr(image, 'supervisor', None)
    if supervisor is None:
        return None
    return PROFILES.get(sha256(supervisor[:0x10000]).hexdigest())


