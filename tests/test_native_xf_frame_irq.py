"""Actual XF source in the native worker, separate from timer/UART polling."""
import ctypes
import struct
from types import SimpleNamespace

import pytest

from courier_emu.dsp import NativeC5x
from courier_emu.machine import CourierMachine
from courier_emu.worker_poll import WorkerPoll
from tests.test_board_service_trace import PollCpu


@pytest.fixture
def source():
    # SETC XF; CLRC XF; IDLE. One genuine falling edge per execution.
    with NativeC5x.from_program(0x6000, struct.pack('<3H', 0xbe4c, 0xbe4d, 0xbe22)) as core:
        m = CourierMachine.__new__(CourierMachine)
        m._use_dsp_xf_int0 = True
        m._frame_hz = None
        m._rom_tick = True
        m._frame_xf_core = None
        m._frame_xf_generation = 0
        m._frame_xf_seen = m._frame_xf_sample = 0
        m._frame_xf_delivered = m._frame_xf_coalesced = 0
        m.frame_instructions, m._last_frame = 1415, 0
        m.dsp_bridge = SimpleNamespace(core=core, boot_rom_enabled=True)
        poll = WorkerPoll()
        s = poll.state
        s.core = core.handle
        s.frame_xf = 1
        s.frame_instructions = s.frame_fallback = 1415
        yield m, core, poll


def pulse(core, count=1):
    for _ in range(count):
        core.set_pc(0x6000)
        core.step(2)


def compare(m, poll, now):
    before = m.dsp_bridge.core.state()
    assert m._frame_irq_due(now) == poll.refresh_frame_cadence(now)
    assert poll.state.frame_xf_seen == m._frame_xf_seen
    assert poll.state.frame_xf_sample == m._frame_xf_sample
    assert poll.state.frame_xf_generation == m._frame_xf_generation
    assert m.dsp_bridge.core.state() == before


def consume(m, poll, now):
    m._consume_frame_irq(now)
    poll.consume_frame(now)
    assert poll.state.frame_xf_seen == m._frame_xf_seen
    assert poll.state.frame_xf_delivered == m._frame_xf_delivered
    assert poll.state.frame_xf_coalesced == m._frame_xf_coalesced
    assert poll.state.last_frame == m._last_frame


def test_native_python_parity_no_fabricated_edges_and_one_pending_request(source):
    m, core, poll = source
    compare(m, poll, 1000000)
    assert not poll.refresh_frame_cadence(1000000)
    pulse(core, 7)
    compare(m, poll, 1000001)
    assert poll.refresh_frame_cadence(1000001)
    consume(m, poll, 1000001)
    assert m._frame_xf_delivered == 1 and m._frame_xf_coalesced == 6
    compare(m, poll, 2000000)
    assert not poll.refresh_frame_cadence(2000000)
    pulse(core)
    compare(m, poll, 2000001)
    consume(m, poll, 2000001)
    assert m._frame_xf_delivered == 2 and m._frame_xf_coalesced == 6


def test_reset_generation_detects_reset_even_when_edge_count_has_caught_up(source):
    m, core, poll = source
    pulse(core, 2)
    compare(m, poll, 100)
    consume(m, poll, 100)
    generation = core.reset_generation()
    assert core.cycle_count() == core.state()['cycles']
    core.reset()
    assert core.cycle_count() == 0
    pulse(core, 2)  # Same count, but these are NEW edges, not the old epoch's.
    assert core.xf_falling_edges() == m._frame_xf_seen == 2
    assert core.reset_generation() != generation
    compare(m, poll, 200)
    assert poll.refresh_frame_cadence(200)
    consume(m, poll, 200)
    assert m._frame_xf_delivered == 2


@pytest.mark.parametrize('step', [16, 64])
@pytest.mark.parametrize('quiet', [False, True])
def test_native_dispatches_xf_between_timer_polls_and_respects_if_and_eoi(source, step, quiet):
    m, core, poll = source
    s = poll.state
    s.armed = s.int0_ok = 1
    s.elide_until = 100000
    s.timer_poll_owed = s.timer_poll_period = 1024
    s.quiet_sip = quiet
    s.batch = 4096 if quiet else 1
    s.cycles_per_x86 = 11.86
    # A harmless partial line batch lets the worker stay native without a
    # socket or resampler; no audio is generated by this tiny DSP program.
    s.line_codec_last = -1
    s.line_min_samples, s.line_max_skip = 2, 1000
    regs = (ctypes.c_uint32 * 14)()
    regs[4], regs[9], regs[10], regs[12] = 0x200, 0x8000, 0x1000, 0x1234
    memory = (ctypes.c_uint8 * (1 << 20))()
    guard = (ctypes.c_uint8 * (1 << 20)).from_buffer_copy(b'\x03' * (1 << 20))
    memory[48:52] = [0x00, 0x04, 0x00, 0x90]
    cpu = PollCpu(regs, ctypes.addressof(memory), len(memory), ctypes.addressof(guard),
                  None, 0, None, 0, 0)
    invoke = ctypes.CFUNCTYPE(ctypes.c_int, ctypes.c_void_p, ctypes.c_uint64,
                             ctypes.c_uint32, ctypes.c_void_p)(poll.function)
    pulse(core, 2)
    assert invoke(poll.context, step, 0, ctypes.byref(cpu)) == 1
    assert s.timer_poll_owed == 1024 - step and s.stack_depth == 0  # IF is clear.
    regs[13] = 0x202
    assert invoke(poll.context, step * 2, 0x202, ctypes.byref(cpu)) == 1
    assert s.timer_poll_owed == 1024 - step * 2  # No general timer poll was performed.
    assert s.frame_xf_delivered == 1 and s.frame_xf_coalesced == 1
    assert s.stack_depth == s.int0_in_service == 1
    assert regs[9] == 0x9000 and regs[12] == 0x400 and regs[4] == 0x1fa
    assert not regs[13] & 0x200
    stack = bytes(memory[0x101fa:0x10200])
    assert struct.unpack('<3H', stack) == (0x1234, 0x8000, 0x202)
    pulse(core)
    regs[13] = 0x202  # Firmware may STI while still in service.
    assert invoke(poll.context, step * 3, 0x202, ctypes.byref(cpu)) == 1
    assert s.frame_xf_delivered == 1 and s.stack_depth == 1
    # The real EOI log, not elapsed time, unblocks the pending frame request.
    eoi = (ctypes.c_uint8 * 8)(2, 255, 0, 0, 0, 128, 2, 0)
    cpu.mmio_events, cpu.mmio_count = ctypes.addressof(eoi), 1
    assert invoke(poll.context, step * 4, 0x202, ctypes.byref(cpu)) == 1
    assert s.timer_poll_owed == 1024 - step * 4
    assert s.frame_xf_delivered == 2 and s.stack_depth == 1
    assert eoi[7] == 1
    if quiet:
        # Only pulse() advanced the DSP. Native quiet passes still recognize
        # XF and EOI at exactly the same CPU instruction boundaries.
        assert core.state()['instructions'] == 6
        assert s.x86_ticks == step * 4
        assert s.debt == s.line_skipped == s.tx_consumed == 0
